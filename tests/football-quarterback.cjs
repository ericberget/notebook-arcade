const assert=require('node:assert/strict');
const L=require('../games/xo-football/league.js');
for(const rr of L.rosters)assert.deepEqual(Object.keys(rr[0].attrs),['speed','arm','accuracy','leadership']);
const qb={role:'QB',attrs:{leadership:99}},wr={role:'WR-L',attrs:{speed:80,hands:98,power:60,arm:50}};
assert.deepEqual(L.effectiveAttrs(wr,qb),{speed:84,hands:99,power:63,arm:50});
assert.equal(wr.attrs.speed,80,'boost does not mutate permanent ratings');
assert.deepEqual(L.effectiveAttrs(wr,{attrs:{leadership:0}}),wr.attrs);
assert.deepEqual(L.effectiveAttrs({...wr,role:'RB'},qb),wr.attrs,'boost only applies to WRs');
assert.deepEqual(L.effectiveAttrs({...wr,role:'TE'},qb),wr.attrs);
assert(Math.hypot(...Object.values(L.passError(95,400,()=>.5)))<Math.hypot(...Object.values(L.passError(40,400,()=>.5))));
assert.equal(Math.hypot(...Object.values(L.passError(99,400,()=>.5))),0);
let saved;global.localStorage={setItem:(_,v)=>saved=v,getItem:()=>saved};
const s=L.create(0,123);L.simDraft(s);const original=s.rosters[0][0],id=original.id;
original.attrs={speed:61,arm:90,hands:82,power:76};
L.save(s);const loaded=L.load();assert.equal(loaded.rosters[0][0].id,id);
assert.deepEqual(loaded.rosters[0][0].attrs,{speed:61,arm:90,accuracy:82,leadership:76});
assert.equal(loaded.draft.picks.length,40);assert.equal(loaded.week,0);
L.save(loaded);assert.deepEqual(L.load(),loaded,'migration is stable after saving');
for(const p of loaded.draft.prospects.filter(p=>p.role==='QB'))assert.deepEqual(Object.keys(p.attrs),['speed','arm','accuracy','leadership']);
console.log('PASS: QB ratings, saved-season migration, leadership cap and scope, immutable WR ratings, accuracy affects throw error');
